#!/usr/bin/env python3
"""Generate the large declarative-memory benchmark models.

The generated files are deterministic.  They live in ``models/generated`` and
are recreated by ``run.py``; they are not checked in.
"""
from __future__ import annotations

import argparse
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
GENERATED = HERE / "models" / "generated"


def _header(name: str, *, partial: bool) -> list[str]:
    params = [
        ":v nil",
        ":model-warnings nil",
        ":style-warnings nil",
        ":trace-detail low",
        ":esc t",
        ":seed (100 0)",
        ":bll nil",
        ":ans nil",
        ":blc 1",
        ":rt -100",
        ":le 0",
        ":lf 0.05",
    ]
    if partial:
        params += [":mas 2", ":mp 10"]
    else:
        params += [":er nil"]
    return [
        f"(define-model {name}",
        "  (sgp " + " ".join(params) + ")",
        "  (chunk-type goal state)",
        "  (chunk-type fact category number)",
    ]


def dm_scan(path: Path, count: int) -> None:
    name = f"bench-dm-scan-{count}"
    lines = _header(name, partial=False)
    lines.append("  (add-dm")
    for j in range(count):
        lines.append(f"    (f{j} isa fact category c0 number {j})")
    lines.append("  )")
    lines.append("  (set-base-levels")
    for j in range(count):
        lines.append(f"    (f{j} {1.0 - j * 0.001:.3f})")
    lines.append("  )")
    lines += [
        "  (define-chunks (s0 isa goal state s0))",
        "  (goal-focus s0)",
        "  (p start",
        "    =goal>",
        "      state s0",
        "    ==>",
        "    =goal>",
        "      state scan",
        "    +retrieval>",
        "      isa fact",
        "      category c0)",
        "  (p loop",
        "    =goal>",
        "      state scan",
        "    =retrieval>",
        "      isa fact",
        "      category =c",
        "    ==>",
        "    +retrieval>",
        "      isa fact",
        "      category =c))",
    ]
    path.write_text("\n".join(lines) + "\n")


def partial_matching(path: Path, count: int) -> None:
    name = f"bench-partial-matching-{count}"
    lines = _header(name, partial=True)
    lines.append("  (add-dm")
    for j in range(count):
        lines.append(f"    (f{j} isa fact category c0 number {j})")
    lines.append("  )")
    lines.append("  (set-base-levels")
    for j in range(count):
        lines.append(f"    (f{j} {1.0 - j * 0.001:.3f})")
    lines.append("  )")
    lines += [
        "  (define-chunks (s0 isa goal state s0))",
        "  (goal-focus s0)",
        "  ;; 9999 is not in memory: every chunk is a partial match on `number`.",
        "  (p start",
        "    =goal>",
        "      state s0",
        "    ==>",
        "    =goal>",
        "      state scan",
        "    +retrieval>",
        "      isa fact",
        "      category c0",
        "      number ~9999)",
        "  (p loop",
        "    =goal>",
        "      state scan",
        "    =retrieval>",
        "      isa fact",
        "      category =c",
        "    ==>",
        "    +retrieval>",
        "      isa fact",
        "      category =c",
        "      number ~9999))",
    ]
    path.write_text("\n".join(lines) + "\n")


def _model_names(paths: list[Path]) -> set[str]:
    names: set[str] = set()
    for path in paths:
        try:
            text = path.read_text(encoding="utf-8", errors="replace")
        except OSError:
            continue
        names.update(
            match.group(1)
            for match in re.finditer(
                r"\(\s*define-model\s+([^\s()]+)", text, re.IGNORECASE
            )
        )
    return names


def write_clear_file(out_dir: Path) -> Path:
    """Delete every model ACT-R would have loaded before the benchmark.

    ACT-R's ``user-loads`` directory is auto-loaded, and the Lisp server has no
    remote ``clear-all`` command.  A small code sidecar loaded with
    ``load-act-r-code`` can call ``(delete-model ...)``; both servers support
    that form, and the Rust server starts empty so it is a no-op there.
    """
    user = sorted((ROOT / "actr7.x" / "user-loads").glob("*.lisp"))
    bench = sorted((HERE / "models").glob("*.lisp")) + sorted(
        (HERE / "models" / "generated").glob("*.lisp")
    )
    names = sorted(_model_names(user + bench))
    lines = [
        ";;; Generated by benchmarking/gen_models.py.  Do not edit.",
        ";;; Remove models auto-loaded by ACT-R (and any prior benchmark model)",
        ";;; before loading the next workload.",
    ]
    lines += [f"(delete-model {name})" for name in names]
    path = out_dir / "clear-user-models.lisp"
    path.write_text("\n".join(lines) + "\n")
    return path


def generate(out_dir: Path | None = None) -> dict[str, Path]:
    """Write every generated model and return ``name -> path``."""
    out_dir = out_dir or GENERATED
    out_dir.mkdir(parents=True, exist_ok=True)
    paths = {
        "dm-scan-200": out_dir / "dm-scan-200.lisp",
        "dm-scan-2000": out_dir / "dm-scan-2000.lisp",
        "partial-matching-2000": out_dir / "partial-matching-2000.lisp",
    }
    dm_scan(paths["dm-scan-200"], 200)
    dm_scan(paths["dm-scan-2000"], 2000)
    partial_matching(paths["partial-matching-2000"], 2000)
    paths["clear-user-models"] = write_clear_file(out_dir)
    return paths


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out-dir", type=Path, default=GENERATED)
    parser.add_argument(
        "--check",
        action="store_true",
        help="regenerate into memory and check the on-disk files match",
    )
    args = parser.parse_args()
    paths = generate(args.out_dir)
    if args.check:
        import tempfile

        with tempfile.TemporaryDirectory() as tmp:
            expected = generate(Path(tmp))
            bad = [
                str(paths[name])
                for name in paths
                if paths[name].read_text() != expected[name].read_text()
            ]
        if bad:
            print("out of date: " + ", ".join(bad))
            return 1
    for name, path in paths.items():
        print(f"{name}: {path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
